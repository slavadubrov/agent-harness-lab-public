"""Rebuild reports/atlas-study/README.md from the study's run files.

    uv run python scripts/report_atlas.py

Per cell (design x harness layer): passes in each trial, pass@1, pass^k for k = the
number of trials, mean dollars and latency per task, and the write guard's decisions.
pass^k is the chance that k attempts at a task all pass, estimated per task as
C(c, k) / C(n, k) from c passes in n trials and averaged over tasks (τ-bench).
"""

from __future__ import annotations

import json
import math
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STUDY = ROOT / "reports" / "atlas-study"
DESIGNS = [
    "plain_workflow",
    "router",
    "agent_in_workflow",
    "agent_with_approval",
    "autonomous_agent",
]
LAYERS = ["base", "sgr_only", "guard_only", "sgr_plus_write_guard"]


def load(folder: Path) -> list[list[dict]]:
    trials = sorted(folder.glob("trial-*"), key=lambda p: int(p.name.split("-")[1]))
    return [
        [json.loads(line) for line in open(t / "results.jsonl")]
        for t in trials
        if (t / "results.jsonl").exists()
    ]


def stats(trials: list[list[dict]]) -> dict:
    n = len(trials)
    tasks = [r["task_id"] for r in trials[0]]
    c = {t: sum(any(r["task_id"] == t and r["passed"] for r in tr) for tr in trials) for t in tasks}
    rows = [r for tr in trials for r in tr]
    return {
        "n": n,
        "passes": [sum(r["passed"] for r in tr) for tr in trials],
        "tasks": len(tasks),
        "pass1": statistics.fmean(v / n for v in c.values()),
        "passk": statistics.fmean(math.comb(v, n) / math.comb(n, n) for v in c.values()),
        "cost": statistics.fmean(r["dollars"] for r in rows),
        "latency": statistics.fmean(r["latency_s"] for r in rows),
        "calls": statistics.fmean(r["model_calls"] for r in rows),
        "tokens": statistics.fmean(r["input_tokens"] for r in rows),
        "blocked": sum(r.get("blocked_tool_calls", 0) for r in rows),
        "flaky": sorted(t for t, v in c.items() if 0 < v < n),
        "always_failed": sorted(t for t, v in c.items() if v == 0),
    }


def commits(folder: Path) -> list[str]:
    out = set()
    for run in folder.glob("trial-*/run.json"):
        out.add(json.loads(run.read_text())["git"]["sha"][:7])
    return sorted(out)


def guard_decisions(folder: Path) -> list[dict]:
    out = []
    for t in sorted(folder.glob("trial-*/traces.jsonl")):
        for line in open(t):
            trace = json.loads(line)
            calls = {}
            for m in trace["messages"]:
                d = m["data"]
                for c in d.get("tool_calls") or []:
                    calls[c["id"]] = c
                g = (d.get("response_metadata") or {}).get("jev_guard")
                if m["type"] == "tool" and g:
                    out.append(
                        {
                            "task": trace["task_id"],
                            "tool": d.get("name"),
                            "args": calls.get(d.get("tool_call_id"), {}).get("args"),
                            **g,
                        }
                    )
    return out


def main() -> None:
    lines = [
        "# Atlas study results",
        "",
        "Generated by `scripts/report_atlas.py` from the run files in this folder. "
        "Observations and limits: [`NOTES.md`](NOTES.md).",
        "",
        "Custom tasks: the 16 Part 2 tasks, `openai/gpt-6-luna` on the pinned OpenAI "
        "endpoint, 5 trials per cell. pass^5 is the chance that five attempts at a task all "
        "pass (τ-bench estimator, averaged over tasks). Dollars are recorded per run at the "
        "run's endpoint price; Jev calls included.",
        "",
        "## Custom tasks (16)",
        "",
        "| design | layer | passes per trial | pass@1 | pass^5 | mean $/task | mean latency s "
        "| mean model calls | mean input tokens | guard blocks | flaky tasks | commits |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for design in DESIGNS:
        for layer in LAYERS:
            folder = STUDY / "custom" / design / layer
            if not folder.exists():
                continue
            s = stats(load(folder))
            lines.append(
                f"| {design} | {layer} | {' '.join(map(str, s['passes']))} of {s['tasks']} "
                f"| {s['pass1']:.3f} | {s['passk']:.3f} | ${s['cost']:.5f} | {s['latency']:.1f} "
                f"| {s['calls']:.1f} | {s['tokens']:,.0f} | {s['blocked']} "
                f"| {', '.join(s['flaky']) or 'none'} | {', '.join(commits(folder))} |"
            )
    lines += [
        "",
        "## Write guard decisions in the task runs",
        "",
        "Every guarded write records Jev's probability (`response_metadata.jev_guard` in "
        "`traces.jsonl`). Blocked calls, by the call that was blocked:",
        "",
        "| design | layer | decisions recorded | blocked | blocked calls |",
        "|---|---|---|---|---|",
    ]
    for design in DESIGNS:
        for layer in ("guard_only", "sgr_plus_write_guard"):
            folder = STUDY / "custom" / design / layer
            if not folder.exists():
                continue
            ds = guard_decisions(folder)
            blocked = [d for d in ds if d["blocked"]]
            kinds = {}
            for d in blocked:
                a = d["args"] or {}
                key = f"{d['tool']}({a.get('order_id', a.get('key', ''))}, "
                key += f"{a.get('amount_cents', a.get('value', ''))}) in {d['task']}"
                kinds[key] = kinds.get(key, 0) + 1
            listed = "; ".join(f"{v} x {k}" for k, v in sorted(kinds.items())) or "none"
            lines.append(f"| {design} | {layer} | {len(ds)} | {len(blocked)} | {listed} |")

    lines += [
        "",
        "## τ³-bench retail (8 tasks)",
        "",
        "| spec | passes per trial | pass@1 | pass^5 | mean agent $/task | mean latency s "
        "| flaky tasks | always failed | commits |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for layer, spec in (
        ("base", "plain.yaml"),
        ("sgr_only", "base.yaml (SGR; the guard never runs under τ³)"),
    ):
        folder = STUDY / "tau3" / layer
        if not folder.exists():
            continue
        s = stats(load(folder))
        lines.append(
            f"| {spec} | {' '.join(map(str, s['passes']))} of {s['tasks']} | {s['pass1']:.3f} "
            f"| {s['passk']:.3f} | ${s['cost']:.5f} | {s['latency']:.1f} "
            f"| {', '.join(s['flaky']) or 'none'} | {', '.join(s['always_failed']) or 'none'} "
            f"| {', '.join(commits(folder))} |"
        )

    guard = STUDY / "guard" / "a1-base"
    if guard.exists():
        info = json.loads((guard / "run.json").read_text())
        rows = [json.loads(line) for line in open(guard / "results.jsonl")]
        s = info["summary_at_threshold"]
        allow = [r["probability"] for r in rows if r["label"] == "allow"]
        block = [r["probability"] for r in rows if r["label"] == "block"]
        lines += [
            "",
            "## Write guard on labelled writes",
            "",
            f"`guard/a1-base/`: {info['cases']} proposed writes x {info['repeats']} repeats, "
            f"the guard from `{info['spec']}`, ${info['dollars']:.4f}.",
            "",
            "| blocked, label block | allowed, label block | allowed, label allow "
            "| blocked, label allow | errors | highest p, label allow | lowest p, label block |",
            "|---|---|---|---|---|---|---|",
            f"| {s['blocked_bad']} | {s['allowed_bad']} | {s['allowed_good']} "
            f"| {s['blocked_good']} | {s['errors']} | {max(allow):.2f} | {min(block):.2f} |",
        ]
    (STUDY / "README.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {STUDY / 'README.md'}")


if __name__ == "__main__":
    main()
